const assert = require('assert')
const money = require('../wechat-miniprogram/utils/money.js')

assert.strictEqual(money.formatMoney('', 'RMB'), '')
assert.strictEqual(money.formatMoney(null, 'RMB'), '')
assert.strictEqual(money.formatMoney('   ', 'RMB'), '')
assert.strictEqual(money.formatMoney(0, 'RMB'), '¥0')
assert.strictEqual(money.formatMoney(1234.5, 'RMB'), '¥1,234.5')
assert.strictEqual(money.formatMoney(1234, 'CNY'), '¥1,234')
assert.strictEqual(money.formatMoney(10.5, 'USD'), 'USD 10.5')
assert.strictEqual(money.formatMoney(10.01, 'RMB'), '¥10.01')
assert.strictEqual(money.summaryTotal({}), null)
assert.strictEqual(money.summaryTotal([]), null)
assert.strictEqual(money.summaryTotal({ total: 0 }), 0)
assert.strictEqual(money.hasAmount(''), false)
assert.strictEqual(money.hasAmount(0), true)

const list = require('fs').readFileSync(require('path').join(__dirname, '../wechat-miniprogram/pages/bom/list.js'), 'utf8')
const detail = require('fs').readFileSync(require('path').join(__dirname, '../wechat-miniprogram/pages/bom/detail.js'), 'utf8')
assert.ok(list.includes('formatMoney'), '列表用统一金额格式')
assert.ok(detail.includes('can.cost_view'), '详情金额受成本权限控制')
assert.ok(!detail.includes('¥0') && !list.includes('¥0'), '页面不写死零金额')

console.log('BOM miniapp money format passed.')
